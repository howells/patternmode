import { existsSync, readFileSync, statSync } from "node:fs";
import path from "node:path";

/**
 * Which source files ship in a registry item, and how they are rewritten for a
 * consumer's tree.
 */

/** A relative specifier in a static import/export or a dynamic `import()`. */
const RELATIVE_SPECIFIER = /(?:from|import)\s*\(?\s*["'](?<spec>\.{1,2}\/[^"']*)["']/gu;

/**
 * @param {string} importer Absolute path of the importing file.
 * @param {string} spec Relative specifier.
 * @param {string} srcDir The package's source root.
 * @returns {string} The absolute file the specifier resolves to.
 */
const resolveRelative = (importer, spec, srcDir) => {
  const base = path.resolve(path.dirname(importer), spec);
  const resolved = [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    `${base}/index.ts`,
    `${base}/index.tsx`,
  ].find((candidate) => existsSync(candidate) && statSync(candidate).isFile());
  if (resolved === undefined) {
    throw new Error(`cannot resolve "${spec}" from ${path.relative(srcDir, importer)}`);
  }
  if (path.relative(srcDir, resolved).startsWith("..")) {
    throw new Error(`"${spec}" in ${path.relative(srcDir, importer)} leaves ${srcDir}`);
  }
  return resolved;
};

/**
 * The files a package ships: its entry files and everything they reach through
 * relative imports. Tests, fixtures and test doubles are never imported by an
 * entry, so they cannot ship whatever they are named.
 * @param {string} srcDir The package's source root.
 * @param {string[]} entries Absolute entry files.
 * @returns {string[]} Absolute file paths, sorted for determinism.
 */
export const collectSourceFiles = (srcDir, entries) => {
  /** @type {Set<string>} */
  const reached = new Set();
  const pending = [...entries];
  for (let file = pending.pop(); file !== undefined; file = pending.pop()) {
    if (reached.has(file)) {
      continue;
    }
    reached.add(file);
    for (const match of readFileSync(file, "utf-8").matchAll(RELATIVE_SPECIFIER)) {
      pending.push(resolveRelative(file, match.groups?.spec ?? "", srcDir));
    }
  }
  return [...reached].toSorted();
};

/**
 * Rewrite internal quoted specifiers (both quote styles) to their vendored
 * `@/` aliases, preserving any subpath after the package name. Specifiers with
 * no target are left for {@link assertNoInternalSpecifiers} to reject.
 * @param {string} source Source text.
 * @param {Map<string, string>} targets Package name to vendored alias.
 * @returns {string} Rewritten source.
 */
const rewriteSpecifiers = (source, targets) =>
  source.replaceAll(
    /(?<quote>["'])(?<spec>@(?:patternmode|howells)\/[^"']+)\k<quote>/gu,
    /**
     * @param {string} full The full quoted match.
     * @param {string} quote The quote character.
     * @param {string} spec The bare specifier.
     * @returns {string} The replacement text.
     */
    (full, quote, spec) => {
      const subpathIndex = spec.indexOf("/", spec.indexOf("/") + 1);
      const pkg = subpathIndex === -1 ? spec : spec.slice(0, subpathIndex);
      const rest = subpathIndex === -1 ? "" : spec.slice(subpathIndex);
      const base = targets.get(pkg);
      return base === undefined ? full : `${quote}${base}${rest}${quote}`;
    },
  );

/**
 * Fail if any internal specifier survived rewriting.
 * @param {string} content Staged file content.
 * @param {string} label File label for the error message.
 * @returns {void}
 */
const assertNoInternalSpecifiers = (content, label) => {
  const match = /(?<specifier>["']@(?:patternmode|howells)\/[^"']*)/u.exec(content);
  if (match?.groups) {
    throw new Error(`unrewritten internal specifier ${match.groups.specifier} in ${label}`);
  }
};

/**
 * Transform a source file for staging: rewrite specifiers, prepend a
 * provenance comment (after a leading `"use client";` directive, if any), and
 * optionally inject a stylesheet import.
 * @param {string} raw Raw source text.
 * @param {object} options Staging options.
 * @param {string} options.sourceLabel `<npm-name>@<version>` provenance label.
 * @param {string} options.fileLabel Human-readable file label for errors.
 * @param {boolean} options.injectStyleImport Whether to inject `import "./styles.css";`.
 * @param {Map<string, string>} options.targets Package name to vendored alias.
 * @returns {string} Transformed content.
 */
export const stageSource = (raw, { fileLabel, injectStyleImport, sourceLabel, targets }) => {
  const lines = rewriteSpecifiers(raw, targets).split("\n");
  const hasDirective = lines[0] === '"use client";' || lines[0] === "'use client';";
  const provenance = `// vendored from ${sourceLabel} — generated by scripts/build-registry.mjs; do not hand-edit.`;
  const insertAt = hasDirective ? 1 : 0;
  lines.splice(insertAt, 0, provenance);
  if (injectStyleImport) {
    lines.splice(insertAt + 1, 0, 'import "./styles.css";');
  }
  const content = lines.join("\n");
  assertNoInternalSpecifiers(content, fileLabel);
  return content;
};
