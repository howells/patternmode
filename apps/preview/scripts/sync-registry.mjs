import { execFileSync, spawn } from "node:child_process";
import { once } from "node:events";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import path from "node:path";

/**
 * Re-vendors the patternmode registry into apps/preview so that stock shadcn
 * components and vendored patternmode components always render against the
 * freshly built local registry. Any generator regression surfaces here on the
 * next build rather than silently drifting.
 *
 * Flow:
 *   1. Rebuild packages/theme/dist/registry via scripts/build-registry.mjs.
 *   2. Serve that directory byte-for-byte over a tiny loopback HTTP server.
 *   3. Run `shadcn add` against the served registry, overwriting the vendored
 *      files under components/patternmode and lib/patternmode.
 *   4. Restore the provenance headers shadcn's `add` transform strips on write.
 *   5. Drop the duplicate `@property` blocks shadcn's css merge re-appends on
 *      every run into app/globals.css.
 */

const nodeProcess = globalThis.process;
const repoRoot = path.resolve(import.meta.dirname, "../../..");
const previewDir = path.resolve(import.meta.dirname, "..");
const themeDir = path.join(repoRoot, "packages", "theme");
const registryDir = path.join(themeDir, "dist", "registry");
const buildRegistryScript = path.join(repoRoot, "scripts", "build-registry.mjs");

const REGISTRY_HOST = "127.0.0.1";
const REGISTRY_PORT = 4787;
const REGISTRY_BASE_URL = `http://${REGISTRY_HOST}:${REGISTRY_PORT}`;

/** Registry items to vendor. Their registryDependencies (system, motion, scrollframe) are pulled in transitively. */
const REGISTRY_ITEMS = [
  "@patternmode/theme",
  "@patternmode/swatch",
  "@patternmode/deck",
  "@patternmode/tags",
  "@patternmode/stacksheet",
];

const PROVENANCE_PATTERN = /^\/\/ vendored from .* generated by scripts\/build-registry\.mjs.*$/mu;

/**
 * @param {unknown} value Candidate value.
 * @returns {value is Record<string, unknown>} Whether the value is a non-null object.
 */
const isRecord = (value) => typeof value === "object" && value !== null;

/**
 * @param {unknown} value Candidate value.
 * @returns {string} A human-readable message for logging.
 */
const messageOf = (value) => (value instanceof Error ? value.message : "unknown error");

/**
 * Rebuild the registry into packages/theme/dist/registry with the loopback base
 * URL baked into every registryDependency.
 * @returns {void}
 */
const buildRegistry = () => {
  execFileSync("node", [buildRegistryScript], {
    cwd: themeDir,
    env: { ...nodeProcess.env, REGISTRY_BASE_URL },
    stdio: "inherit",
  });
};

/**
 * Start a loopback static server exposing `<registryDir>/<name>.json` at
 * `/r/<name>.json`, byte-for-byte from disk — no transforms, so shadcn consumes
 * exactly what the production registry would serve. Throws a clear error if the
 * port is already taken.
 * @returns {Promise<import("node:http").Server>} The listening server.
 */
const startRegistryServer = async () => {
  const server = createServer((request, response) => {
    const url = new URL(request.url ?? "/", REGISTRY_BASE_URL);
    const match = /^\/r\/(?<name>[a-z0-9-]+)\.json$/u.exec(url.pathname);
    const name = match?.groups?.name;
    const filePath = name === undefined ? undefined : path.join(registryDir, `${name}.json`);

    if (filePath === undefined || !existsSync(filePath)) {
      response.writeHead(404, { "content-type": "application/json" });
      response.end('{"error":"not found"}');
      return;
    }

    response.writeHead(200, { "content-type": "application/json" });
    response.end(readFileSync(filePath));
  });

  server.listen(REGISTRY_PORT, REGISTRY_HOST);
  try {
    await once(server, "listening");
  } catch (error) {
    if (isRecord(error) && error.code === "EADDRINUSE") {
      throw new Error(
        `Registry port ${REGISTRY_PORT} is already in use. Stop whatever is bound to ${REGISTRY_BASE_URL} and re-run.`,
        { cause: error },
      );
    }
    throw new Error("failed to start registry server", { cause: error });
  }
  return server;
};

/**
 * Run the pinned shadcn CLI (packages/theme devDep) to add every registry item
 * into apps/preview, overwriting the vendored files.
 *
 * Must not block the event loop: the registry server lives in this same process,
 * so a synchronous spawn would deadlock shadcn's own HTTP requests back to it.
 * @returns {Promise<void>} Resolves when shadcn exits 0, throws otherwise.
 */
const runShadcnAdd = async () => {
  const child = spawn(
    "pnpm",
    [
      "--dir",
      themeDir,
      "exec",
      "shadcn",
      "add",
      "--yes",
      "--overwrite",
      ...REGISTRY_ITEMS,
      "--cwd",
      previewDir,
    ],
    { cwd: previewDir, stdio: "inherit" },
  );
  await once(child, "close");
  if (child.exitCode !== 0) {
    throw new Error(`shadcn add exited with code ${String(child.exitCode)}`);
  }
};

/**
 * Re-insert a provenance header into one written file if shadcn stripped it.
 * @param {string} target Registry-relative target path.
 * @param {string} provenance The provenance comment line to ensure.
 * @returns {void}
 */
const ensureProvenanceInFile = (target, provenance) => {
  const absolute = path.join(previewDir, target);
  if (!existsSync(absolute)) {
    return;
  }
  const current = readFileSync(absolute, "utf-8");
  if (current.includes(provenance)) {
    return;
  }
  const lines = current.split("\n");
  const hasDirective = lines[0] === '"use client";' || lines[0] === "'use client';";
  lines.splice(hasDirective ? 1 : 0, 0, provenance);
  writeFileSync(absolute, lines.join("\n"));
};

/**
 * Restore the per-file provenance headers that shadcn's `add` transform strips.
 *
 * build-registry.mjs prepends `// vendored from <pkg>@<version> — generated by …`
 * to every staged file, but shadcn drops that leading detached comment from any
 * file whose first token is not a `"use client"` directive. The built registry
 * JSON is the source of truth, so re-read each item's `content`, recover the
 * provenance line, and re-insert it into the written file when shadcn removed it.
 * @returns {void}
 */
const restoreProvenanceHeaders = () => {
  for (const jsonFile of readdirSync(registryDir)) {
    if (!jsonFile.endsWith(".json") || jsonFile === "registry.json") {
      continue;
    }
    /** @type {unknown} */
    const item = JSON.parse(readFileSync(path.join(registryDir, jsonFile), "utf-8"));
    if (!isRecord(item) || !Array.isArray(item.files)) {
      continue;
    }
    for (const file of item.files) {
      if (!isRecord(file)) {
        continue;
      }
      const { content, target } = file;
      if (typeof target !== "string" || typeof content !== "string") {
        continue;
      }
      const provenance = PROVENANCE_PATTERN.exec(content)?.[0];
      if (provenance !== undefined) {
        ensureProvenanceInFile(target, provenance);
      }
    }
  }
};

/**
 * Drop repeated identical top-level `@property` blocks from app/globals.css.
 *
 * shadcn's css merge dedupes `@import`/`@plugin` at-rules but appends non-empty
 * at-rules unconditionally, so the scrollframe item's `@property` registrations
 * accumulate one copy per `add`. Keeps the first occurrence of each block.
 * @returns {void}
 */
const dedupeAppendedAtRules = () => {
  const cssPath = path.join(previewDir, "app", "globals.css");
  const css = readFileSync(cssPath, "utf-8");
  const seen = new Set();
  const deduped = css
    .replaceAll(/@property\s+--[\w-]+\s*\{[^{}]*\}\n?/gu, (block) => {
      const key = block.trim();
      if (seen.has(key)) {
        return "";
      }
      seen.add(key);
      return block;
    })
    .replaceAll(/\n{3,}/gu, "\n\n");
  if (deduped !== css) {
    writeFileSync(cssPath, deduped, "utf-8");
  }
};

/**
 * Re-format the preview-owned stylesheet that shadcn rewrites on every `add`.
 *
 * shadcn re-emits `app/globals.css` (cssVars/css merge) in its own formatting
 * each run, which fails the repo formatter. This normalizes it back to house
 * style — the vendored registry output is untouched. `app/layout.tsx` is no
 * longer touched: shadcn's font wiring only fires for `registry:font` items,
 * and `font-inter` is a plain `registry:item` now.
 * @returns {void}
 */
const formatShadcnTouchedAppFiles = () => {
  execFileSync("pnpm", ["exec", "oxfmt", "app/globals.css"], {
    cwd: previewDir,
    stdio: "inherit",
  });
};

/**
 * Entry point.
 * @returns {Promise<void>}
 */
const main = async () => {
  buildRegistry();

  const server = await startRegistryServer();
  try {
    await runShadcnAdd();
    restoreProvenanceHeaders();
    // Format before deduping so freshly-appended @property blocks (shadcn's
    // 4-space style) byte-match the existing 2-space ones; format again to
    // collapse the blank lines the dedupe leaves behind.
    formatShadcnTouchedAppFiles();
    dedupeAppendedAtRules();
    formatShadcnTouchedAppFiles();
  } finally {
    server.close();
    await once(server, "close");
  }
};

try {
  await main();
} catch (error) {
  console.error(messageOf(error));
  nodeProcess.exitCode = 1;
}
